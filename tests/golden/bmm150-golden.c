// Generates golden test vectors for the Toit BMM150 driver.
//
// This program includes Bosch Sensortec's own BMM150 sensor API source and
// feeds it synthetic trim bytes and raw register bytes. The numbers it prints
// are what Bosch's code computes, so the Toit driver can be compared against
// them without any hardware.
//
// Build and run (needs the Bosch API files in ../../.reference):
//   gcc -std=gnu99 -I../../.reference -o bmm150-golden bmm150-golden.c -lm
//   ./bmm150-golden > ../golden-vectors.toit
//
// The Bosch source is not part of the published package. It is licensed by
// Bosch Sensortec and is kept locally in .reference/ only.

#define BMM150_USE_FLOATING_POINT
#include <stdio.h>
#include <stdint.h>
#include <string.h>
#include <math.h>

#include "bmm150.c"

// The fake bus. It serves the chip ID, the trim registers 0x5D to 0x71 and the
// data registers 0x42 to 0x49. Everything else reads 0.
static uint8_t fake_regs[0x80];

static BMM150_INTF_RET_TYPE fake_read(uint8_t reg, uint8_t *buf, uint32_t len,
                                       void *intf) {
  (void) intf;
  for (uint32_t i = 0; i < len; i++) buf[i] = fake_regs[(reg + i) & 0x7F];
  return 0;
}

static BMM150_INTF_RET_TYPE fake_write(uint8_t reg, const uint8_t *buf,
                                        uint32_t len, void *intf) {
  (void) reg; (void) buf; (void) len; (void) intf;
  return 0;
}

static void fake_delay(uint32_t us, void *intf) { (void) us; (void) intf; }

static uint32_t lcg_state = 0x150;
static uint32_t lcg(void) {
  lcg_state = lcg_state * 1664525u + 1013904223u;
  return lcg_state >> 8;
}

static void print_bytes(const uint8_t *bytes, int count) {
  printf("#[");
  for (int i = 0; i < count; i++) printf("%s0x%02x", i ? ", " : "", bytes[i]);
  printf("]");
}

// raw is x, y, z (signed) and rhall (unsigned 14 bits).
static void print_case(const char *name, const uint8_t *trim,
                       const int32_t *raw) {
  struct bmm150_dev dev;
  memset(&dev, 0, sizeof(dev));
  dev.read = fake_read;
  dev.write = fake_write;
  dev.delay_us = fake_delay;
  dev.intf = BMM150_I2C_INTF;
  dev.intf_ptr = fake_regs;  // Bosch only checks that it is not null.

  memset(fake_regs, 0, sizeof(fake_regs));
  fake_regs[0x40] = 0x32;
  memcpy(fake_regs + 0x5D, trim, 21);

  // X and Y: 13 bits, 5 in bits 7..3 of the LSB byte. Bit 0 is the self-test
  // flag, which the real chip sets to 1. Z: 15 bits, 7 in bits 7..1.
  fake_regs[0x42] = ((raw[0] & 0x1F) << 3) | 1;
  fake_regs[0x43] = (raw[0] >> 5) & 0xFF;
  fake_regs[0x44] = ((raw[1] & 0x1F) << 3) | 1;
  fake_regs[0x45] = (raw[1] >> 5) & 0xFF;
  fake_regs[0x46] = ((raw[2] & 0x7F) << 1) | 1;
  fake_regs[0x47] = (raw[2] >> 7) & 0xFF;
  fake_regs[0x48] = ((raw[3] & 0x3F) << 2) | 1;  // Bit 0 is data ready.
  fake_regs[0x49] = (raw[3] >> 6) & 0xFF;

  int8_t result = bmm150_init(&dev);
  if (result != BMM150_OK) {
    fprintf(stderr, "bmm150_init failed for %s: %d\n", name, result);
    return;
  }
  struct bmm150_mag_data mag;
  result = bmm150_read_mag_data(&mag, &dev);
  if (result != BMM150_OK) {
    fprintf(stderr, "bmm150_read_mag_data failed for %s: %d\n", name, result);
    return;
  }

  printf("  {\n");
  printf("    \"name\": \"%s\",\n", name);
  printf("    // Registers 0x5D to 0x71.\n");
  printf("    \"trim\": "); print_bytes(trim, 21); printf(",\n");
  printf("    // Registers 0x42 to 0x49.\n");
  printf("    \"bytes\": "); print_bytes(fake_regs + 0x42, 8); printf(",\n");
  printf("    // x, y, z and the Hall resistance, as the driver should decode them.\n");
  printf("    \"raw\": [%d, %d, %d, %d],\n", raw[0], raw[1], raw[2], raw[3]);
  printf("    // The trim values as Bosch's code decoded them.\n");
  printf("    \"decoded\": [%d, %d, %d, %d, %u, %d, %d, %d, %u, %d, %u],\n",
         dev.trim_data.dig_x1, dev.trim_data.dig_y1, dev.trim_data.dig_x2,
         dev.trim_data.dig_y2, dev.trim_data.dig_z1, dev.trim_data.dig_z2,
         dev.trim_data.dig_z3, dev.trim_data.dig_z4, dev.trim_data.dig_xy1,
         dev.trim_data.dig_xy2, dev.trim_data.dig_xyz1);
  printf("    \"mag\": [%.9g, %.9g, %.9g],\n", mag.x, mag.y, mag.z);
  printf("  },\n");
}

int main(void) {
  printf("// Copyright (C) 2026 Toit Contributors\n");
  printf("// Use of this source code is governed by a Zero-Clause BSD license that can\n");
  printf("// be found in the EXAMPLES_LICENSE file.\n\n");
  printf("// Generated by tests/golden/bmm150-golden.c from Bosch Sensortec's BMM150\n");
  printf("// sensor API. Do not edit by hand.\n\n");
  printf("GOLDEN-CASES ::= [\n");

  // A set that looks like a real chip: the Hall resistance is close to xyz1,
  // so the correction term is small.
  uint8_t typical[21] = {0};
  typical[0x00] = 0xFD;  // x1 = -3.
  typical[0x01] = 0xFB;  // y1 = -5.
  typical[0x05] = 0x20; typical[0x06] = 0x00;  // z4 = 32.
  typical[0x07] = 0x0A;  // x2 = 10.
  typical[0x08] = 0x0C;  // y2 = 12.
  typical[0x0B] = 0xC0; typical[0x0C] = 0x0B;  // z2 = 3008 (0x0BC0).
  typical[0x0D] = 0x10; typical[0x0E] = 0x27;  // z1 = 10000.
  typical[0x0F] = 0x18; typical[0x10] = 0x16;  // xyz1 = 5656.
  typical[0x11] = 0xFC; typical[0x12] = 0xFF;  // z3 = -4.
  typical[0x13] = 0x01;  // xy2 = 1.
  typical[0x14] = 0x32;  // xy1 = 50.
  int32_t typical_raw[4] = {120, -85, 310, 5700};
  print_case("typical trims and field", typical, typical_raw);

  int32_t negative_raw[4] = {-2000, 1500, -7000, 5500};
  print_case("typical trims, strong negative field", typical, negative_raw);

  // The MSB of xyz1 is not part of the value, and the driver must mask it.
  uint8_t masked[21];
  memcpy(masked, typical, 21);
  masked[0x10] |= 0x80;
  print_case("xyz1 with its top bit set", masked, typical_raw);

  // Pseudo-random trims and readings, all with non-zero trims so that Bosch's
  // code does not take its overflow branch.
  for (int n = 1; n <= 6; n++) {
    uint8_t trim[21];
    for (int i = 0; i < 21; i++) trim[i] = lcg() & 0xFF;
    trim[0x0F] |= 1;                       // xyz1 stays non-zero.
    trim[0x10] = 0x10 + (trim[0x10] & 0x0F);
    trim[0x0D] |= 1;                       // z1 non-zero.
    trim[0x0C] |= 0x01;                    // z2 non-zero.
    int32_t raw[4];
    raw[0] = (int32_t) (lcg() % 8000) - 4000;
    raw[1] = (int32_t) (lcg() % 8000) - 4000;
    raw[2] = (int32_t) (lcg() % 30000) - 15000;
    raw[3] = 3000 + (int32_t) (lcg() % 6000);
    char name[40];
    snprintf(name, sizeof(name), "pseudo-random trims %d", n);
    print_case(name, trim, raw);
  }

  printf("]\n");
  return 0;
}
